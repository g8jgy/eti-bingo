// Writes supabase/setup.sql: the ETI Bingo game server as Postgres tables + functions for a free
// Supabase project. Paste the file into the Supabase SQL Editor and run it. Safe to re-run: tables
// are kept, functions are replaced and the round pools are refreshed from lib/content.js.
// Usage: node tools/build-supabase-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { roundPool, POOL_SIZE } from '../lib/content.js';
import { ROUNDS } from '../lib/engine.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const pools = Object.fromEntries(ROUNDS.map((r) => [r, roundPool(r)]));

export const SQL = `-- ETI Bingo game server for Supabase (generated by tools/build-supabase-sql.mjs; do not hand-edit).
-- Run the whole file in the Supabase SQL Editor. Safe to re-run.
-- Then set your host passphrase (the big-screen controls refuse to work until you do):
--   update bingo.config set value = to_jsonb('your passphrase'::text) where key = 'host_key';
--
-- Tables live in the private "bingo" schema, which the Supabase API does not expose. Phones and the host
-- screen only call the public bingo_* functions below, which check every move on the server.

create schema if not exists bingo;

create table if not exists bingo.config (key text primary key, value jsonb not null);
create table if not exists bingo.game (
  id int primary key default 1 check (id = 1),
  v int not null default 1,
  status text not null default 'lobby',
  round int not null default 1,
  draws jsonb not null default '[]'          -- [{id, r, n, sq, at}], at = reveal time in epoch ms
);
create table if not exists bingo.players (
  id text primary key,
  tok text not null,
  name text not null,
  r int not null default 0,                  -- round the current card was dealt for
  cells int[] not null default '{}',         -- 25 square indexes, -1 = free center (Postgres arrays are 1-based)
  marks int[] not null default '{}',         -- marked cell positions, 0-based like the client
  togo int not null default 4,               -- squares still needed for a line
  rounds jsonb not null default '{}',        -- marks kept per round when the round changes
  won int not null default 0,
  lm bigint not null default 0,
  joined bigint not null default 0
);
create table if not exists bingo.wins (
  round int primary key,
  player_id text not null,
  at bigint not null,
  crowned boolean not null default false
);
alter table bingo.config enable row level security;
alter table bingo.game enable row level security;
alter table bingo.players enable row level security;
alter table bingo.wins enable row level security;
revoke all on schema bingo from public, anon, authenticated;

insert into bingo.game (id) values (1) on conflict do nothing;
insert into bingo.config values ('host_key', to_jsonb('CHANGE-ME'::text)) on conflict (key) do nothing;
insert into bingo.config values ('pools', '${JSON.stringify(pools)}'::jsonb)
  on conflict (key) do update set value = excluded.value;
insert into bingo.config values ('spin_ms', '3500'::jsonb) on conflict (key) do nothing;

-- ------------------------------------------------------------------ helpers (private)
create or replace function bingo.now_ms() returns bigint language sql volatile as $$
  select (extract(epoch from clock_timestamp()) * 1000)::bigint
$$;

create or replace function bingo.rand_id(n int) returns text language sql volatile as $$
  select left(replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', ''), n)
$$;

-- Squares still needed for any line (0 = BINGO). The center (cell 12) is always free.
create or replace function bingo.to_go(marks int[]) returns int language sql immutable as $$
  select min(cnt)::int from (
    select l.k, count(*) filter (where c <> 12 and not (c = any(marks))) as cnt
    from (values (1, array[0,1,2,3,4]), (2, array[5,6,7,8,9]), (3, array[10,11,12,13,14]), (4, array[15,16,17,18,19]),
                 (5, array[20,21,22,23,24]), (6, array[0,5,10,15,20]), (7, array[1,6,11,16,21]), (8, array[2,7,12,17,22]),
                 (9, array[3,8,13,18,23]), (10, array[4,9,14,19,24]), (11, array[0,6,12,18,24]), (12, array[4,8,12,16,20])) as l(k, cells),
         unnest(l.cells) as c
    group by l.k) t
$$;

-- Squares revealed so far this round (a draw is hidden until the host screen finishes its spin).
create or replace function bingo.called(g bingo.game, now_ms bigint) returns int[] language sql stable as $$
  select coalesce(array_agg((d->>'sq')::int order by (d->>'n')::int), '{}')
  from jsonb_array_elements((g).draws) as t(d)
  where (d->>'r')::int = (g).round and (d->>'at')::bigint <= now_ms
$$;

-- Deal the player's card for a round: 24 random squares from that round's pool plus the free center.
-- Marks for the round being left are kept, so going back to a round restores them.
create or replace function bingo.deal(p bingo.players, rnd int) returns bingo.players language plpgsql volatile as $$
declare
  pool jsonb := (select value -> rnd::text from bingo.config where key = 'pools');
  pick int[];
begin
  if p.r = rnd and cardinality(p.cells) = 25 then return p; end if;
  if p.r > 0 then p.rounds := p.rounds || jsonb_build_object(p.r::text, to_jsonb(p.marks)); end if;
  select array_agg(x) into pick from (select x::int from jsonb_array_elements_text(pool) t(x) order by random() limit 24) s;
  p.cells := pick[1:12] || array[-1] || pick[13:24];
  p.marks := coalesce((select array_agg(x::int) from jsonb_array_elements_text(p.rounds -> rnd::text) t(x)), '{}');
  p.togo := bingo.to_go(p.marks);
  p.r := rnd;
  return p;
end $$;

create or replace function bingo.public_player(p bingo.players) returns jsonb language sql stable as $$
  select jsonb_build_object('id', (p).id, 'name', (p).name, 'round', (p).r, 'cells', to_jsonb((p).cells),
                            'marks', to_jsonb((p).marks), 'won', (p).won)
$$;

create or replace function bingo.fail(msg text, kind text default 'rule') returns void language plpgsql as $$
begin
  raise exception using message = msg, hint = kind;  -- the client maps hint 'auth' to 401, anything else to 409
end $$;

create or replace function bingo.auth(p_pid text, p_tok text) returns bingo.players language plpgsql volatile as $$
declare p bingo.players;
begin
  select * into p from bingo.players where id = p_pid for update;
  if not found or p.tok is distinct from p_tok then perform bingo.fail('Card not found. Rejoin from the QR code.', 'auth'); end if;
  return p;
end $$;

create or replace function bingo.save(p bingo.players) returns void language sql volatile as $$
  update bingo.players set r = (p).r, cells = (p).cells, marks = (p).marks, togo = (p).togo, rounds = (p).rounds, won = (p).won, lm = (p).lm
  where id = (p).id
$$;

-- Leaderboard order: players still eligible first, then fewest to go, most marked, name.
create or replace function bingo.standings() returns table(rank int, id text, name text, marks int, togo int, won int)
language sql stable as $$
  select (row_number() over w)::int, p.id, p.name, coalesce(cardinality(p.marks), 0), p.togo, p.won
  from bingo.players p
  window w as (order by (p.won > 0), p.togo, cardinality(p.marks) desc, p.name)
  order by 1
$$;

-- ------------------------------------------------------------------ public API (called by the pages)
create or replace function public.bingo_state() returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  now_ms bigint := bingo.now_ms();
  g bingo.game;
  called int[];
  last jsonb;
  cur jsonb := null;
  rows jsonb;
begin
  select * into g from bingo.game where id = 1;
  called := bingo.called(g, now_ms);
  select d into last from jsonb_array_elements(g.draws) as t(d) where (d->>'r')::int = g.round order by (d->>'n')::int desc limit 1;
  if last is not null then
    if now_ms >= (last->>'at')::bigint then
      cur := jsonb_build_object('id', last->'id', 'n', last->'n', 'at', last->'at', 'sq', last->'sq',
        'onCards', (select count(*) from bingo.players p where (last->>'sq')::int = any(p.cells)));
    else
      cur := jsonb_build_object('id', last->'id', 'n', last->'n', 'at', last->'at', 'sq', null, 'onCards', null);
    end if;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('rank', s.rank, 'id', s.id, 'name', s.name, 'marks', s.marks, 'toGo', s.togo, 'won', s.won) order by s.rank), '[]')
    into rows from bingo.standings() s;
  return jsonb_build_object(
    'now', now_ms, 'v', g.v, 'status', g.status, 'round', g.round,
    'drawCount', cardinality(called), 'called', to_jsonb(called), 'left', ${POOL_SIZE} - cardinality(called),
    'current', cur,
    'wins', coalesce((select jsonb_object_agg(w.round::text, jsonb_build_object('id', w.player_id, 'name', coalesce(p.name, 'Player'), 'at', w.at))
                      from bingo.wins w left join bingo.players p on p.id = w.player_id), '{}'),
    'players', jsonb_array_length(rows),
    'top', coalesce((select jsonb_agg(x - 'rank') from (select x from jsonb_array_elements(rows) as t(x) limit 10) q), '[]'),
    'st', coalesce((select jsonb_object_agg(x->>'id', jsonb_build_array(x->'rank', x->'toGo', x->'marks')) from jsonb_array_elements(rows) as t(x)), '{}'));
end $$;

create or replace function public.bingo_join(p_name text) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  nm text := left(btrim(regexp_replace(regexp_replace(coalesce(p_name, ''), '[[:cntrl:]<>]', '', 'g'), '\\s+', ' ', 'g')), 32);
  g bingo.game;
  p bingo.players;
begin
  if char_length(nm) < 2 then perform bingo.fail('Please enter your name.'); end if;
  select * into g from bingo.game where id = 1;
  p.id := bingo.rand_id(12); p.tok := bingo.rand_id(32); p.name := nm; p.r := 0; p.cells := '{}'; p.marks := '{}';
  p.rounds := '{}'; p.won := 0; p.lm := 0; p.joined := bingo.now_ms();
  p := bingo.deal(p, g.round);
  insert into bingo.players select (p).*;
  return jsonb_build_object('pid', p.id, 'token', p.tok, 'player', bingo.public_player(p), 'now', bingo.now_ms());
end $$;

create or replace function public.bingo_me(p_pid text, p_tok text) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare g bingo.game; p bingo.players; d bingo.players;
begin
  select * into g from bingo.game where id = 1;
  p := bingo.auth(p_pid, p_tok);
  d := bingo.deal(p, g.round);
  if d.r <> p.r then perform bingo.save(d); end if;
  return jsonb_build_object('player', bingo.public_player(d), 'now', bingo.now_ms());
end $$;

-- Mark one cell. Only squares that have been called this round can be marked.
create or replace function public.bingo_mark(p_pid text, p_tok text, p_cell int) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare now_ms bigint := bingo.now_ms(); g bingo.game; p bingo.players;
begin
  select * into g from bingo.game where id = 1;
  p := bingo.auth(p_pid, p_tok);
  if p.r <> g.round then perform bingo.save(bingo.deal(p, g.round)); perform bingo.fail('New round, new card! Look again.'); end if;
  if p_cell is null or p_cell < 0 or p_cell > 24 or p_cell = 12 then perform bingo.fail('Pick a square.'); end if;
  if not (p.cells[p_cell + 1] = any(bingo.called(g, now_ms))) then perform bingo.fail('That square hasn''t been called yet.'); end if;
  if not (p_cell = any(p.marks)) then
    p.marks := p.marks || p_cell; p.togo := bingo.to_go(p.marks); p.lm := now_ms;
    perform bingo.save(p);
  end if;
  return jsonb_build_object('player', bingo.public_player(p));
end $$;

-- Press BINGO. Wins the round if a line is complete and nobody beat you to it (the round is the wins key).
create or replace function public.bingo_claim(p_pid text, p_tok text) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare g bingo.game; p bingo.players; got int;
begin
  select * into g from bingo.game where id = 1;
  p := bingo.auth(p_pid, p_tok);
  if p.r <> g.round then perform bingo.save(bingo.deal(p, g.round)); perform bingo.fail('New round, new card! Look again.'); end if;
  if p.won > 0 then perform bingo.fail(format('You already won Round %s. Let someone else have a turn!', p.won)); end if;
  if bingo.to_go(p.marks) > 0 then perform bingo.fail(format('Not yet! You need any line for Round %s.', g.round)); end if;
  insert into bingo.wins (round, player_id, at) values (g.round, p.id, bingo.now_ms()) on conflict do nothing;
  get diagnostics got = row_count;
  if got = 0 then perform bingo.fail('So close! Someone called BINGO first this round.'); end if;
  p.won := g.round;
  perform bingo.save(p);
  return jsonb_build_object('won', g.round, 'player', bingo.public_player(p));
end $$;

-- Host controls. Every call carries the host passphrase.
create or replace function public.bingo_host(p_key text, p_op text, p_args jsonb default '{}') returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  hk text := (select value #>> '{}' from bingo.config where key = 'host_key');
  spin bigint := coalesce((select (value #>> '{}')::bigint from bingo.config where key = 'spin_ms'), 3500);
  pools jsonb := (select value from bingo.config where key = 'pools');
  now_ms bigint := bingo.now_ms();
  g bingo.game; p bingo.players; d jsonb; last jsonb; sq int; n int; rnd int; cnt int; idx int; w bingo.wins;
begin
  if hk is null or hk = 'CHANGE-ME' then perform bingo.fail('Set the host passphrase in Supabase first (see the top of setup.sql).', 'auth'); end if;
  if p_key is distinct from hk then perform bingo.fail('Wrong host key.', 'auth'); end if;
  p_args := coalesce(p_args, '{}');
  select * into g from bingo.game where id = 1 for update;

  if p_op = 'check' then
    return jsonb_build_object('ok', true, 'backend', 'supabase');

  elsif p_op = 'draw' then
    select x into last from jsonb_array_elements(g.draws) as t(x) order by (x->>'at')::bigint desc limit 1;
    if last is not null and now_ms < (last->>'at')::bigint then perform bingo.fail('Still drawing.'); end if;
    select x::int into sq from jsonb_array_elements_text(pools -> g.round::text) t(x)
      where x::int not in (select (y->>'sq')::int from jsonb_array_elements(g.draws) as u(y) where (y->>'r')::int = g.round)
      order by random() limit 1;
    if sq is null then perform bingo.fail('Every square has been called.'); end if;
    select count(*) + 1 into n from jsonb_array_elements(g.draws) as u(y) where (y->>'r')::int = g.round;
    d := jsonb_build_object('id', format('d%s-%s-%s', g.round, n, bingo.rand_id(4)), 'r', g.round, 'n', n, 'sq', sq, 'at', now_ms + spin);
    update bingo.game set draws = draws || jsonb_build_array(d), status = 'live', v = v + 1 where id = 1;
    return jsonb_build_object('draw', jsonb_build_object('id', d->'id', 'n', d->'n', 'at', d->'at'));

  elsif p_op = 'undo' then
    select (o - 1)::int, x into idx, last from jsonb_array_elements(g.draws) with ordinality t(x, o)
      where (x->>'r')::int = g.round order by (x->>'n')::int desc limit 1;
    if last is null then perform bingo.fail('Nothing to undo this round.'); end if;
    update bingo.game set draws = draws - idx, v = v + 1 where id = 1;
    return jsonb_build_object('undone', last->'sq', 'note', 'Players who already marked it keep the mark.');

  elsif p_op = 'round' then
    rnd := (p_args->>'round')::int;
    if rnd is null or not (pools ? rnd::text) then perform bingo.fail(format('Round must be 1 to %s.', (select count(*) from jsonb_object_keys(pools)))); end if;
    cnt := 0;
    for p in select * from bingo.players for update loop
      if p.r <> rnd then perform bingo.save(bingo.deal(p, rnd)); cnt := cnt + 1; end if;
    end loop;
    update bingo.game set round = rnd, v = v + 1 where id = 1;
    return jsonb_build_object('round', rnd, 'dealt', cnt);

  elsif p_op = 'crown' then
    if exists (select 1 from bingo.wins where round = g.round) then perform bingo.fail('This round already has a winner, or nobody is eligible.'); end if;
    select * into p from bingo.players where won = 0 order by togo, cardinality(marks) desc, name limit 1 for update;
    if not found then perform bingo.fail('This round already has a winner, or nobody is eligible.'); end if;
    insert into bingo.wins (round, player_id, at, crowned) values (g.round, p.id, now_ms, true);
    p.won := g.round; perform bingo.save(p);
    update bingo.game set v = v + 1 where id = 1;
    return jsonb_build_object('winner', jsonb_build_object('id', p.id, 'name', p.name));

  elsif p_op = 'clear-win' then
    rnd := (p_args->>'round')::int;
    delete from bingo.wins where round = rnd returning * into w;
    if w.player_id is null then perform bingo.fail('No winner recorded for that round.'); end if;
    update bingo.players set won = 0 where id = w.player_id;
    update bingo.game set v = v + 1 where id = 1;
    return jsonb_build_object('cleared', rnd);

  elsif p_op = 'settings' then
    if p_args->>'status' in ('lobby', 'live', 'ended') then
      update bingo.game set status = p_args->>'status', v = v + 1 where id = 1;
    end if;
    return jsonb_build_object('status', coalesce(p_args->>'status', g.status));

  elsif p_op = 'kick' then
    delete from bingo.players where id = p_args->>'pid';
    return jsonb_build_object('removed', p_args->>'pid');

  elsif p_op = 'reset' then
    if p_args->>'confirm' is distinct from 'RESET' then perform bingo.fail('Type RESET to confirm.'); end if;
    delete from bingo.wins where true;
    delete from bingo.players where true;
    update bingo.game set v = v + 1, status = 'lobby', round = 1, draws = '[]' where id = 1;
    return jsonb_build_object('reset', true);

  elsif p_op = 'players' then
    return jsonb_build_object('players', coalesce((select jsonb_agg(jsonb_build_object('rank', s.rank, 'id', s.id, 'name', s.name,
      'marks', s.marks, 'toGo', s.togo, 'won', s.won) order by s.rank) from bingo.standings() s), '[]'));

  else
    perform bingo.fail('Unknown operation.');
  end if;
  return null;
end $$;

-- Phones and the host screen use the anon (publishable) key; they may only run the public functions.
revoke all on all functions in schema bingo from public, anon, authenticated;
revoke all on function public.bingo_state(), public.bingo_join(text), public.bingo_me(text, text),
  public.bingo_mark(text, text, int), public.bingo_claim(text, text), public.bingo_host(text, text, jsonb) from public;
grant execute on function public.bingo_state(), public.bingo_join(text), public.bingo_me(text, text),
  public.bingo_mark(text, text, int), public.bingo_claim(text, text), public.bingo_host(text, text, jsonb) to anon, authenticated;
`;

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = path.join(root, 'supabase', 'setup.sql');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, SQL);
  console.log('wrote', out, Math.round(SQL.length / 1024) + ' KB');
}
